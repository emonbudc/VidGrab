package com.vidgrab.app.core.model

import java.io.File
import java.util.Locale

/** The MIME type Media3 and our downloader use for a caption file extension. */
fun subtitleMimeForExt(ext: String): String = when (ext.lowercase().substringAfterLast('.')) {
    "vtt", "webvtt" -> "text/vtt"
    "srt" -> "application/x-subrip"
    "ass", "ssa" -> "text/x-ssa"
    "ttml", "xml" -> "application/ttml+xml"
    else -> "text/vtt"
}

/** File extension for a caption MIME type. */
fun subtitleExtForMime(mimeType: String): String = when (mimeType.lowercase()) {
    "text/vtt", "text/webvtt" -> "vtt"
    "application/x-subrip", "text/srt" -> "srt"
    "text/x-ssa", "text/x-ass" -> "ass"
    "application/ttml+xml", "application/xml", "text/xml" -> "ttml"
    else -> "vtt"
}

/** A readable caption name: the site's label, or the locale's display name. */
fun subtitleLabel(language: String, autoGenerated: Boolean, siteLabel: String? = null): String {
    val base = siteLabel?.takeIf { it.isNotBlank() }
        ?: runCatching { Locale.forLanguageTag(language.replace('_', '-')).getDisplayName(Locale.getDefault()) }
            .getOrNull()?.takeIf { it.isNotBlank() }
        ?: language.ifBlank { "Subtitles" }
    return if (autoGenerated && !base.contains("auto", ignoreCase = true)) "$base (auto-generated)" else base
}

/**
 * The one caption track to use by default: the preferred language if available, then English, then the first
 * manual track, then the first auto-generated one. Auto-generated tracks never win over manual ones.
 */
fun pickSubtitle(tracks: List<SubtitleTrack>, preferredLanguage: String = ""): SubtitleTrack? {
    if (tracks.isEmpty()) return null
    val preferred = preferredLanguage.ifBlank { Locale.getDefault().language }.substringBefore('-').lowercase()
    fun matching(language: String) = tracks.filter { it.baseLanguage == language }
    fun best(list: List<SubtitleTrack>) = list.firstOrNull { !it.autoGenerated } ?: list.firstOrNull()
    return best(matching(preferred))
        ?: (if (preferred != "en") best(matching("en")) else null)
        ?: tracks.firstOrNull { !it.autoGenerated }
        ?: tracks.first()
}

private val SIDECAR_EXTENSIONS = setOf("vtt", "srt", "ass", "ssa", "ttml")

/** Caption files stored next to [videoFile], such as "Movie.en.vtt" or "Movie.srt". */
fun sidecarSubtitles(videoFile: File): List<SubtitleTrack> {
    val parent = videoFile.parentFile ?: return emptyList()
    val base = videoFile.nameWithoutExtension
    return parent.listFiles().orEmpty()
        .filter { it.isFile && it.extension.lowercase() in SIDECAR_EXTENSIONS }
        .filter { it.nameWithoutExtension == base || it.name.startsWith("$base.") }
        .mapNotNull { file ->
            val suffix = file.nameWithoutExtension.removePrefix(base).trimStart('.')
            val language = suffix.substringBefore('.').ifBlank { "und" }
            val mime = subtitleMimeForExt(file.extension)
            SubtitleTrack(
                language,
                subtitleLabel(language, false, if ("forced" in suffix.lowercase()) "Forced" else null),
                file.toURI().toString(),
                mime,
            )
        }
        .distinctBy { it.url }
        .sortedBy { it.label }
}
